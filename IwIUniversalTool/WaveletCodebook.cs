        public static byte[] Generate()
        {
            var data = new byte[TableSize];
            for (int n = 0; n < Codes.Length; n++)
            {
                int tableIndex = Table[n];
                int len = Lens[n];
                int code = Codes[n];
                int mask = (1 << len) - 1;
                int baseOffset = tableIndex * 16384;

                for (int i = 0; i < 4096; i++)
                {
                    if ((i & mask) != code) continue;
                    int offset = baseOffset + i * 4;
                    BinaryPrimitives.WriteInt16LittleEndian(data.AsSpan(offset, 2), Vals[n]);
                    BinaryPrimitives.WriteUInt16LittleEndian(data.AsSpan(offset + 2, 2), (ushort)len);
                }
            }
            return data;
        }
